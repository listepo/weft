const BENCH = fileURLToPath(new URL("../", import.meta.url));
const RESULTS = `${BENCH}results/`;

function usage(): never {
  console.error(
    [
      "usage: node bench/src/run.ts tokens",
      "       node bench/src/run.ts edit|read [--provider anthropic|openai] [--base-url <url>] [--model a,b]",
      `                                       [--screens a,b] [--formats ${FORMATS.join(",")}] [--samples 3]`,
      "                                       [--concurrency 4] [--batch] [--readback]",
      "                                       [--resume <results.json>] [--estimate]",
      "       node bench/src/run.ts rescore <results.json>",
      "",
      "--provider openai talks to any OpenAI-compatible server; --base-url defaults to LM Studio",
      `(${LMSTUDIO_URL}) and --model is required. --batch uses the Anthropic Message Batches API.`,
      "--readback sends one plain-language binding diff after a valid edit, for every format.",
      "--resume sends only the jobs a saved run of the same options lacks and saves them merged.",
      "--estimate sends nothing and prints the requests and proxy input tokens the run would send.",
      `--formats also takes ${ALL_FORMATS.filter((f) => !FORMATS.includes(f as never)).join(", ")}; the constrained one is edit-only.`,
    ].join("\n"),
  );
  process.exit(2);
}

async function tokensCommand(): Promise<void> {
  const apiKey = process.env.ANTHROPIC_API_KEY;
  const anthropic: AnthropicOptions | undefined = apiKey
    ? { apiKey, model: DEFAULT_MODELS[0] }
    : undefined;
  const table = await measure(anthropic);
  const primers = FORMATS.map((f) => `| ${f} | ${countProxy(PRIMERS[f])} |`).join("\n");
  const body = renderTokenTable(table);
  const report = [
    "# Weft benchmark report",
    "",
    "Generated by `node bench/src/run.ts tokens`. The 12 corpus screens in `corpus/` describe the same content in four formats; see `corpus/README.md` for how the formats were written and where A2UI could not express a screen.",
    "",
    "## Size of the corpus",
    "",
    body,
    "## Prompt primers",
    "",
    `Format primers used by the edit and read runs, in ${PROXY_TOKENIZER} tokens:`,
    "",
    "| Format | Primer tokens |",
    "| --- | ---: |",
    primers,
    "",
  ].join("\n");
  mkdirSync(RESULTS, { recursive: true });
  writeFileSync(`${RESULTS}tokens.md`, body);
  writeFileSync(`${RESULTS}tokens.json`, JSON.stringify(table, null, 2) + "\n");
  writeFileSync(`${BENCH}REPORT.md`, report);
  console.log(report);
}

interface TaskOptions {
  provider?: string;
  "base-url"?: string;
  model?: string;
  screens?: string;
  formats?: string;
  samples?: string;
  concurrency?: string;
  batch?: boolean;
  readback?: boolean;
  resume?: string;
  estimate?: boolean;
}

const positiveInt = (v: string | undefined, fallback: number): number => {
  if (v === undefined) return fallback;
  const n = Number(v);
  if (!Number.isInteger(n) || n < 1) usage();
  return n;
};

function modelsOf(values: TaskOptions): string[] {
  const kind = values.provider ?? "anthropic";
  if (kind === "openai") {
    if (values.batch || !values.model) usage();
    return values.model.split(",");
  }
  if (kind !== "anthropic") usage();
  return values.model ? values.model.split(",") : [...DEFAULT_MODELS];
}

function providers(values: TaskOptions): (m: string) => Provider {
  if (values.provider === "openai") {
    const baseUrl = values["base-url"] ?? LMSTUDIO_URL;
    const apiKey = process.env.OPENAI_API_KEY;
    return (model) => openAiProvider({ baseUrl, model, ...(apiKey ? { apiKey } : {}) });
  }
  const apiKey = process.env.ANTHROPIC_API_KEY;
  if (!apiKey) {
    console.error(
      "ANTHROPIC_API_KEY is not set: Anthropic runs call the Messages API. Use --provider openai for a local server; `run.ts tokens` works offline.",
    );
    process.exit(2);
  }
  // One batching provider per model, so each batch holds a single model's requests.
  const batched = new Map<string, Provider>();
  return (model) => {
    if (!values.batch) return anthropicProvider({ apiKey, model });
    if (!batched.has(model))
      batched.set(
        model,
        batchingProvider((prompts) => {
          console.error(`${model}: batch of ${prompts.length} requests submitted`);
          return anthropicBatch({ apiKey, model }, prompts);
        }),
      );
    return batched.get(model) as Provider;
  };
}

/**
 * A provider that cannot take the document schema whole is reported as unsupported, before any
 * paid call, rather than sent a reduced schema (creator's answer to T12.3 question 2).
 */
function refuseUnsupported(mode: string, formats: Format[], values: TaskOptions): void {
  const schema = formats.map(schemaFor).find((s) => s !== undefined);
  if (!schema) return;
  if (mode !== "edit") {
    console.error("weft-json-constrained runs only in edit mode: a read reply is not a document.");
    process.exit(2);
  }
  if (values.batch) {
    console.error("weft-json-constrained cannot run with --batch: batch requests carry no schema.");
    process.exit(2);
  }
  if ((values.provider ?? "anthropic") !== "anthropic") return;
  const problems = anthropicSchemaProblems(schema);
  if (problems.length === 0) return;
  console.error(
    `weft-json-constrained is unsupported on Anthropic; the document schema breaks its structured-output limits:\n${problems.map((p) => `- ${p}`).join("\n")}`,
  );
  process.exit(2);
}

function save(mode: string, stamp: string, title: string, results: TaskResult[]): string {
  const summary = renderSummary(title, summarize(results));
  mkdirSync(RESULTS, { recursive: true });
  writeFileSync(`${RESULTS}${mode}-${stamp}.json`, JSON.stringify(results, null, 2) + "\n");
  writeFileSync(`${RESULTS}${mode}-${stamp}.md`, summary);
  return summary;
}

async function tasksCommand(mode: "edit" | "read", values: TaskOptions): Promise<void> {
  const formats = (values.formats ? values.formats.split(",") : [...FORMATS]) as Format[];
  for (const f of formats) if (!ALL_FORMATS.includes(f)) usage();
  refuseUnsupported(mode, formats, values);
  const models = modelsOf(values);
  const screens = values.screens ? values.screens.split(",") : [...SCREENS];
  const samples = positiveInt(values.samples, 3);
  // A batch is only formed from requests issued together, so batch mode starts every job at once.
  const concurrency = values.batch ? Number.MAX_SAFE_INTEGER : positiveInt(values.concurrency, 4);
  const type = mode === "edit" ? "edit" : "question";
  const tasks = loadTasks().filter((t) => t.type === type && screens.includes(t.screen));
  const jobs = planJobs(tasks, formats, models, samples);
  // Ctrl-C saves what finished as a partial run, so a long local run can be split across sessions.
  const stop = new AbortController();
  const interrupt = () => stop.abort(new Error("interrupted"));
  process.once("SIGINT", interrupt);
  process.once("SIGTERM", interrupt);
  const options = { readback: values.readback === true, signal: stop.signal };
  const saved = values.resume
    ? (JSON.parse(readFileSync(values.resume, "utf8")) as TaskResult[])
    : [];
  const { kept, remaining } = resumeJobs(jobs, saved, options);
  if (values.estimate) {
    console.log(renderEstimate(estimateJobs(remaining)));
    return;
  }
  // Looked up only now, so an estimate needs no API key.
  const providerFor = providers(values);
  const stamp = new Date().toISOString().replace(/[:.]/g, "-");
  let done = kept.length;
  const run = await runJobs(
    remaining,
    providerFor,
    concurrency,
    (r) =>
      console.error(
        `[${++done}/${jobs.length}] ${r.model} ${r.id} ${r.format} #${r.sample}: ${r.success ? "ok" : "FAIL"}`,
      ),
    options,
  );
  const results = [...kept, ...run.results];
  const error = run.error;
  // The merged file names its source, so the History row can say which run it continues.
  const from = values.resume ? `, resumed from ${values.resume.split("/").pop()}` : "";
  if (error !== undefined) {
    console.log(
      save(
        mode,
        stamp,
        `${mode} run (partial: ${results.length} of ${jobs.length}${from})`,
        results,
      ),
    );
    throw error;
  }
  console.log(save(mode, stamp, `${mode} run${from ? ` (${from.slice(2)})` : ""}`, results));
}

function rescoreCommand(file: string | undefined): void {
  if (!file) usage();
  const saved = JSON.parse(readFileSync(file, "utf8")) as TaskResult[];
  const results = rescore(saved, loadTasks());
  const kept = results.filter((r, i) => r === saved[i]).length;
  const base = file.replace(/\.json$/, "");
  writeFileSync(`${base}.rescored.json`, JSON.stringify(results, null, 2) + "\n");
  const summary = renderSummary(`rescore of ${base.split("/").pop()}`, summarize(results));
  writeFileSync(`${base}.rescored.md`, summary);
  if (kept) console.error(`${kept} results have no saved reply and keep their original verdict`);
  console.log(summary);
}

const { positionals, values } = parseArgs({
  allowPositionals: true,
  options: {
    provider: { type: "string" },
    "base-url": { type: "string" },
    model: { type: "string" },
    screens: { type: "string" },
    formats: { type: "string" },
    samples: { type: "string" },
    concurrency: { type: "string" },
    batch: { type: "boolean" },
    readback: { type: "boolean" },
    resume: { type: "string" },
    estimate: { type: "boolean" },
  },
});
const command = positionals[0];
if (command === "tokens") await tokensCommand();
else if (command === "edit" || command === "read") await tasksCommand(command, values);
else if (command === "rescore") rescoreCommand(positionals[1]);
else usage();
