// The slint-bindings checkout Cargo made of the `rev` pinned in Cargo.toml. That rev is the only
// pin (T69.1 decision 2): the C# control and the Swift package come from the same commit as the
// `sb_*` calls linked into weft-studio-ffi, so the three languages cannot drift apart.
//
//   node studio/scripts/slint-bindings.ts            prints the checkout
//   node studio/scripts/slint-bindings.ts --msbuild  writes studio/windows/SlintBindings.g.props
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

export const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
export const msbuildProps = join(repoRoot, "studio/windows/SlintBindings.g.props");

interface Metadata {
  packages: { name: string; manifest_path: string }[];
}

/** The checkout's root: `crates/slint-bindings-ffi/Cargo.toml` sits two folders below it. */
export const slintBindingsDir = (): string => {
  const text = execFileSync("cargo", ["metadata", "--format-version", "1", "--locked"], {
    cwd: repoRoot,
    encoding: "utf8",
    maxBuffer: 1 << 28,
  });
  const ffi = (JSON.parse(text) as Metadata).packages.find((p) => p.name === "slint-bindings-ffi");
  if (!ffi) throw new Error("cargo metadata lists no slint-bindings-ffi");
  return resolve(dirname(ffi.manifest_path), "../..");
};

/** The MSBuild properties file `studio/windows/Directory.Build.props` imports. */
export const writeMsbuildProps = (dir: string = slintBindingsDir()): string => {
  // MSBuild joins `$(SlintBindingsDir)windows\...`, so the folder ends with a separator.
  const folder = dir.endsWith(sep) ? dir : `${dir}${sep}`;
  const escaped = folder.replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;");
  writeFileSync(
    msbuildProps,
    `<!-- Generated by studio/scripts/slint-bindings.ts. Do not edit. -->
<Project>
  <PropertyGroup>
    <SlintBindingsDir>${escaped}</SlintBindingsDir>
  </PropertyGroup>
</Project>
`,
  );
  return msbuildProps;
};

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  console.log(process.argv.includes("--msbuild") ? writeMsbuildProps() : slintBindingsDir());
}
